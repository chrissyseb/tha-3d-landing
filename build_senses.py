#!/usr/bin/env python3
"""Build api/_senses.js: ranked everyday senses per word for My Lists.
For each dictionary word, WordNet (OEWN 2024) senses are scored so the sense a student expects comes first:
  - WordNet sense order (earlier = better), within the word's dominant part of speech (from the CEFR list in _dict.js)
  - corpus fit: overlap between each sense's gloss/lemmas/hypernyms and everyday Tatoeba sentences using the word
  - lexicographer-file bonus for concrete school-topic senses (animals, objects, food, plants, time, nature)
  - penalties for archaic, informal, slang, derogatory, technical/domain-labelled, proper-noun and person-insult senses
Output row per word: [[pos, gloss, bagOfWords], ...] best first (up to 4). Also a confidence margin flag.
Usage: python3 build_senses.py api/_dict.js api/_senses.js"""
import json, re, sys, collections
import wn
DICTJS, OUT = sys.argv[1], sys.argv[2]
src = open(DICTJS).read()
DICT = json.loads(json.loads(re.search(r'JSON\.parse\((".*?")\);\n', src, re.S).group(1)))
o = wn.Wordnet('oewn:2024')
STOP = set('the a an and or but if of to in on at by for with from as is are was were be been it its this that these those he she they we you i me my our your his her their them not no do does did have has had will would can could should may might must so than too very just also there here what which who when where why how all any some each more most much many other such into over under about after before up down out off only one something someone used especially usually etc'.split())
tok = lambda s: [t for t in re.findall(r"[a-z]+", s.lower()) if t not in STOP and len(t) > 2]
# everyday corpus contexts
CTX = collections.defaultdict(list)
for line in open('/tmp/fe/data/fra.txt', encoding='utf-8'):
    en = line.split('\t', 1)[0]
    ts = set(re.findall(r"[a-z]+", en.lower()))
    for t in ts:
        if len(CTX[t]) < 150: CTX[t].append(ts)
GOOD = {'noun.animal': 1.4, 'noun.object': .8, 'noun.artifact': .4, 'noun.food': .9, 'noun.plant': 1.3, 'noun.time': .8, 'noun.phenomenon': .5,
        'noun.body': .6, 'noun.location': .3, 'noun.substance': .4, 'noun.feeling': .5, 'noun.communication': .2, 'noun.event': .3,
        'verb.motion': .4, 'verb.perception': .4, 'verb.body': .3, 'verb.consumption': .4, 'verb.creation': .3, 'verb.communication': .3, 'adj.all': .3}
BAD = {'noun.person': -1.0, 'noun.attribute': -.4, 'noun.relation': -.5, 'noun.quantity': -.3, 'adj.pert': -.8}
REG = re.compile(r"\b(archaic|obsolete|informal|slang|vulgar|derogatory|offensive|disparaging|colloquial|dialect|chiefly british|old-fashioned|literary|baseball|cricket|golf|football|nautical|military|law|legal|medicine|pathology|anatomy|chemistry|physics|genetics|biology|botany|zoology|computer|mathematics|statistics|linguistics|grammar|music|poker|card game|gambling|heraldry|theology|roe|ecclesiastical|printing|economics|finance|stock exchange)\b", re.I)
def senses(w, p):
    ss = o.synsets(w, pos=p) + (o.synsets(w, pos='s') if p == 'a' else [])
    return ss
def clean(d):
    d = re.sub(r'\s*\(.*?\)', '', d or '').strip(' ;')
    if len(d) > 90: d = d[:d.rfind(' ', 0, 88)] + '…'
    return d
out, low = {}, 0
for r in DICT:
    w, pos = r[0], r[2]
    if not pos: continue
    cands = []
    for p in ['n', 'v', 'a', 'r']:
        ss = senses(w, p)
        for i, s in enumerate(ss[:8]):
            raw = s.definition() or ''
            d = clean(raw)
            if not d: continue
            bag = set(tok(raw + ' ' + ' '.join(s.examples()) + ' ' + ' '.join(l for l in s.lemmas() if l != w)))
            for h in s.hypernyms()[:2]: bag |= set(tok(' '.join(h.lemmas()) + ' ' + (h.definition() or '')))
            bag.discard(w)
            ctx = CTX.get(w, [])
            fit = sum(len(bag & c) for c in ctx) / (len(ctx) + 3) if ctx else 0
            sc = -0.55 * i + 2.0 * min(fit, 1.5) + GOOD.get(s.lexfile(), 0) + BAD.get(s.lexfile(), 0)
            if p != pos: sc -= 3.0
            if REG.search(raw) or re.search(r'\(.*\b[A-Z]', raw) and False: sc -= 1.5
            if re.search(r'(?<!^)\b[A-Z][a-z]{2,}', raw): sc -= 1.2  # proper names / regions
            if len(s.lemmas()) and w not in s.lemmas(): continue
            extra = sorted(bag - set(tok(d)), key=len)[:8]
            cands.append((sc, p, d, extra))
    if not cands: continue
    cands.sort(key=lambda t: -t[0])
    # dedupe glosses
    seen, top = set(), []
    for c in cands:
        if c[2] in seen: continue
        seen.add(c[2]); top.append(c)
    multi = len([c for c in top if c[1] == pos]) > 1
    margin = top[0][0] - top[1][0] if len(top) > 1 else 9
    sure = 1 if (not multi or margin >= 0.9) else 0
    low += (1 - sure)
    if multi or top[0][2] != r[3]:
        out[w] = [sure] + [[c[1], c[2], ' '.join(c[3])] for c in top[:3]]
js = '// Auto-generated by build_senses.py from Open English WordNet 2024 (CC BY 4.0) + Tatoeba contexts. Row: [sure(0/1), [pos, gloss, contextWords], ...] best sense first.\nexport const SENSES = JSON.parse(' + json.dumps(json.dumps(out, separators=(',', ':'), ensure_ascii=False)) + ');\n'
open(OUT, 'w').write(js)
print(len(out), 'words', 'unsure', low, round(len(js) / 1e6, 2), 'MB')
